export function passCStats() {
  const rows = mesoCulturalCorrespondences;
  const byDomain: Record<string, number> = {};
  for (const r of rows) byDomain[r.domain] = (byDomain[r.domain] ?? 0) + 1;
  return {
    total: rows.length,
    target: MESO_PASS_C_META.target,
    high: rows.filter((r) => r.strength === "high").length,
    medium: rows.filter((r) => r.strength === "medium").length,
    low: rows.filter((r) => r.strength === "low").length,
    contested: rows.filter((r) => r.contested).length,
    byDomain,
    pctOfTarget: Math.round((rows.length / MESO_PASS_C_META.target) * 1000) / 10,
  };
}

export function getPassC() {
  const stats = passCStats();
  return {
    meta: MESO_PASS_C_META,
    correspondences: mesoCulturalCorrespondences,
    stats,
    loaded: stats.total >= 400,
    complete: stats.total >= stats.target,
  };
}
