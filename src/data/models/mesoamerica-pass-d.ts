export function passDStats() {
  const sites = mesoSiteCorrelations;
  return {
    totalSites: sites.length,
    eras: mesoEraSlices.length,
    high: sites.filter((s) => s.confidence === "high").length,
    medium: sites.filter((s) => s.confidence === "medium").length,
    low: sites.filter((s) => s.confidence === "low").length,
    contested: sites.filter((s) => s.contested).length,
    linkedPassA: sites.filter((s) => s.passAIds.length > 0).length,
    contrastPins: sites.filter((s) => s.bomFeatures.length === 0).length,
  };
}

export function getPassD() {
  const stats = passDStats();
  return {
    meta: MESO_PASS_D_META,
    eras: mesoEraSlices,
    sites: mesoSiteCorrelations,
    stats,
    loaded: stats.totalSites >= 25 && stats.eras === 4,
    complete: stats.totalSites >= 25,
  };
}

/** Lightweight GeoJSON-like features for future Map Lab site layer */
export function passDSiteFeatures() {
  return mesoSiteCorrelations.map((s) => ({
    type: "Feature" as const,
    geometry: { type: "Point" as const, coordinates: [s.lng, s.lat] },
    properties: {
      id: s.id,
      name: s.siteName,
      confidence: s.confidence,
      contested: s.contested,
      bomFeatures: s.bomFeatures,
      correlation: s.correlation,
    },
  }));
}
