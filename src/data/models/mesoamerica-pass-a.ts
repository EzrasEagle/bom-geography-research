export function passAStats() {
  return {
    total: mesoMapCorrespondences.length,
    high: mesoMapCorrespondences.filter((c) => c.confidence === "high").length,
    medium: mesoMapCorrespondences.filter((c) => c.confidence === "medium").length,
    low: mesoMapCorrespondences.filter((c) => c.confidence === "low").length,
    contested: mesoMapCorrespondences.filter((c) => c.contested).length,
  };
}

/** Constraints derived from Pass A for Map Lab / catalog */
export function passAConstraints() {
  return mesoMapCorrespondences
    .filter((c) => c.mapLab === "constraint" || c.mapLab === "both")
    .map((c) => ({
      id: c.id,
      from: c.bomFeatures[0] ?? "unknown",
      to: c.bomFeatures[1] ?? c.bomFeatures[0] ?? "unknown",
      type: "map_correspondence",
      value: c.claim,
      sourceVerse: c.verseHints[0],
      strength: c.confidence === "high" && !c.contested ? ("hard" as const) : ("soft" as const),
      correspondenceN: c.n,
      realWorld: c.realWorld,
    }));
}
